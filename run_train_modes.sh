#!/bin/bash

set -euo pipefail

export all_proxy=http://127.0.0.1:7890
# export CUDA_VISIBLE_DEVICES=0

# Auto-train selected paper baselines by repeatedly invoking `bash run.sh`.
#
# Default modes:
#   1) nocamera : blind baseline, zero depth input
#   2) ours     : learned camera + full sensor gradient
#   3) nondiff  : learned camera + detached sensor gradient
#   4) fix      : fixed camera baseline
#   5) randfix  : random static camera baseline
#
# Examples:
#   bash run_train_modes.sh
#   BASE_CONFIG=configs/paper_final_full.args MODES="ours nondiff" bash run_train_modes.sh

BASE_CONFIG=${BASE_CONFIG:-configs/paper_final_full.args}
MODES=${MODES:-"ours"}
PREFIX=${PREFIX:-$(basename "${BASE_CONFIG%.args}")_auto}

if [ ! -f "$BASE_CONFIG" ]; then
	echo "[error] base config not found: $BASE_CONFIG"
	exit 1
fi

make_override_block() {
	local mode="$1"
	case "$mode" in
		nocamera)
			cat <<'EOF'
# auto-generated mode overrides: nocamera
--policy_depth_mode zero
--camera_control_mode fixed
--sensor_grad_mode detached
--no-include_camera_state_in_obs
EOF
			;;
		ours)
			cat <<'EOF'
# auto-generated mode overrides: ours
--policy_depth_mode depth
--camera_control_mode learned
--sensor_grad_mode full
EOF
			;;
		nondiff)
			cat <<'EOF'
# auto-generated mode overrides: nondiff
--policy_depth_mode depth
--camera_control_mode learned
--sensor_grad_mode detached
EOF
			;;
		fix)
			cat <<'EOF'
# auto-generated mode overrides: fix
--policy_depth_mode depth
--camera_control_mode fixed
--sensor_grad_mode full
EOF
			;;
		randfix|fixed_random|fixed_random_static)
			cat <<'EOF'
# auto-generated mode overrides: randfix
--policy_depth_mode depth
--camera_control_mode fixed_random_static
--sensor_grad_mode full
EOF
			;;
		*)
			echo "[error] unsupported mode: $mode" >&2
			return 1
			;;
	esac
}

generated_tasks=()

for mode in $MODES; do
	task_name="${PREFIX}_${mode}"
	task_file="configs/${task_name}.args"
	cp "$BASE_CONFIG" "$task_file"
	{
		echo
		echo "# ================================================================"
		echo "# Generated by run_train_modes.sh"
		echo "# mode: ${mode}"
		echo "# base_config: ${BASE_CONFIG}"
		echo "# ================================================================"
		make_override_block "$mode"
	} >> "$task_file"
	generated_tasks+=("$task_name")

	echo "[train-suite] mode=${mode} task=${task_name}"
	echo "[train-suite] config=${task_file}"
	TASK="$task_name" bash run.sh
done

echo
echo "[train-suite] completed modes:"
for task_name in "${generated_tasks[@]}"; do
	echo "  - ${task_name}"
done
